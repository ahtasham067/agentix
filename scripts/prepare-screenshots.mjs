#!/usr/bin/env node
// Turns the owner's project pictures into web-ready WebP files.
//
//   node scripts/prepare-screenshots.mjs --src "/path/to/images"
//
// Reads scripts/screenshots.manifest.json. Sources under --src are only read,
// never changed. For each picture it hides private data (redact: pixelate and
// blur), paints over dev-tool badges (patch), trims edge artifacts, caps the
// width at 1600 px and writes public/projects/<slug>/<name>.webp at quality 80
// (lowered in steps to 70 if the file would exceed 300 KB). It then writes
// src/content/projects/screenshots.generated.ts with size, alt, caption and a
// tiny blur placeholder for next/image.
import { execFileSync } from "node:child_process";
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import sharp from "sharp";

const ROOT = resolve(import.meta.dirname, "..");
const MAX_WIDTH = 1600;
const MAX_BYTES = 300 * 1024;
const QUALITIES = [80, 76, 72, 70];

function arg(name) {
  const i = process.argv.indexOf(name);
  return i === -1 ? undefined : process.argv[i + 1];
}

const src = arg("--src");
if (!src) {
  console.error('Usage: node scripts/prepare-screenshots.mjs --src "<images folder>"');
  process.exit(1);
}

const manifest = JSON.parse(readFileSync(join(ROOT, "scripts/screenshots.manifest.json"), "utf8"));

/** Pixelate, then blur, so text in the box cannot be read back. */
async function redactTile(input, { x, y, w, h }) {
  const small = await sharp(input)
    .extract({ left: x, top: y, width: w, height: h })
    .resize(Math.max(1, Math.round(w / 10)), Math.max(1, Math.round(h / 10)))
    .toBuffer();
  return sharp(small).resize(w, h, { kernel: "nearest" }).blur(4).png().toBuffer();
}

async function patchTile(input, { w, h, from }) {
  const { data, info } = await sharp(input).raw().toBuffer({ resolveWithObject: true });
  const i = (from.y * info.width + from.x) * info.channels;
  const background = { r: data[i], g: data[i + 1], b: data[i + 2] };
  return sharp({ create: { width: w, height: h, channels: 3, background } })
    .png()
    .toBuffer();
}

async function prepare(slug, entry) {
  const input = readFileSync(join(src, entry.source));
  const composites = [];
  for (const box of entry.redact ?? []) {
    composites.push({ input: await redactTile(input, box), left: box.x, top: box.y });
  }
  for (const box of entry.patch ?? []) {
    composites.push({ input: await patchTile(input, box), left: box.x, top: box.y });
  }
  let image = sharp(input).flatten({ background: "#ffffff" });
  if (composites.length) image = sharp(await image.composite(composites).png().toBuffer());

  const meta = await image.metadata();
  const t = { top: 0, right: 0, bottom: 0, left: 0, ...entry.trim };
  const cropped = await image
    .extract({
      left: t.left,
      top: t.top,
      width: meta.width - t.left - t.right,
      height: meta.height - t.top - t.bottom,
    })
    .resize({ width: MAX_WIDTH, withoutEnlargement: true })
    .png()
    .toBuffer();

  let out;
  let quality;
  for (quality of QUALITIES) {
    out = await sharp(cropped).webp({ quality, effort: 6 }).toBuffer();
    if (out.length <= MAX_BYTES) break;
  }
  if (out.length > MAX_BYTES) {
    throw new Error(`${entry.name}: ${out.length} bytes is over the 300 KB limit`);
  }

  const file = join(ROOT, "public/projects", slug, `${entry.name}.webp`);
  mkdirSync(dirname(file), { recursive: true });
  writeFileSync(file, out);

  const { width, height } = await sharp(out).metadata();
  const blur = await sharp(cropped).resize(10).webp({ quality: 50 }).toBuffer();
  console.log(
    `${slug}/${entry.name}.webp ${width}x${height} q${quality} ${(out.length / 1024).toFixed(0)} KB`,
  );
  return {
    src: `/projects/${slug}/${entry.name}.webp`,
    alt: entry.alt,
    caption: entry.caption,
    width,
    height,
    blurDataURL: `data:image/webp;base64,${blur.toString("base64")}`,
  };
}

const result = {};
for (const [slug, entries] of Object.entries(manifest.projects)) {
  result[slug] = [];
  for (const entry of entries) result[slug].push(await prepare(slug, entry));
}

const target = join(ROOT, "src/content/projects/screenshots.generated.ts");
writeFileSync(
  target,
  `// Generated by scripts/prepare-screenshots.mjs from scripts/screenshots.manifest.json. Do not edit.
import type { Screenshot } from "../types";

export const screenshots = ${JSON.stringify(result, null, 2)} satisfies Record<string, Screenshot[]>;
`,
);
execFileSync("npx", ["prettier", "--write", target], { cwd: ROOT, stdio: "ignore" });
console.log(`Wrote ${target}`);
